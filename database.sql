CREATE DATABASE IF NOT EXISTS logitrack CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE logitrack;
CREATE TABLE IF NOT EXISTS products (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, sku VARCHAR(60), weight DECIMAL(10,2) NOT NULL DEFAULT 0, quantity INT NOT NULL DEFAULT 1, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS transporters (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, document VARCHAR(30), phone VARCHAR(30), vehicle VARCHAR(100), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS addresses (
 id INT AUTO_INCREMENT PRIMARY KEY, label VARCHAR(100) NOT NULL, street VARCHAR(180) NOT NULL, city VARCHAR(100) NOT NULL, state CHAR(2) NOT NULL, zip VARCHAR(12), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS freights (
 id INT AUTO_INCREMENT PRIMARY KEY, transporter_id INT NOT NULL, origin_id INT NOT NULL, destination_id INT NOT NULL, freight_date DATE NOT NULL, status VARCHAR(30) NOT NULL DEFAULT 'Planejado', notes TEXT,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (transporter_id) REFERENCES transporters(id),
 FOREIGN KEY (origin_id) REFERENCES addresses(id),
 FOREIGN KEY (destination_id) REFERENCES addresses(id)
);
CREATE TABLE IF NOT EXISTS freight_products (
 id INT AUTO_INCREMENT PRIMARY KEY, freight_id INT NOT NULL, product_id INT NOT NULL, quantity INT NOT NULL DEFAULT 1,
 FOREIGN KEY (freight_id) REFERENCES freights(id) ON DELETE CASCADE,
 FOREIGN KEY (product_id) REFERENCES products(id)
);
